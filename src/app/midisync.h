// Unified MIDI clock and transport ownership (FM Buddy 2.0, S7).
// Centralizes realtime clock/transport handling so Play and Sequencer share one timing authority
// without competing MIDI clock masters. Realtime dispatch reaches this module independently of
// MIDI thru/routing (S7.1); this module decides how/when to drive consumers.
#pragma once

#include <stdint.h>

namespace midi { typedef void (*Out)(int d, const uint8_t* msg, uint32_t n); }

namespace midisync {

enum Mode : uint8_t {
  MODE_INTERNAL = 0,     // fm1buddy is clock master (standalone)
  MODE_EXTERNAL_MIDI,    // follow incoming MIDI Clock/transport from a device
  MODE_HOST_MIDI,        // follow host-provided clock where verified (treated as external input)
  MODES
};

enum SourceKind : uint8_t { SRC_NONE = 0, SRC_INTERNAL, SRC_DEVICE, SRC_HOST };

enum Transport : uint8_t { TR_STOPPED = 0, TR_PLAYING, TR_CONTINUE_PENDING };

// Snapshot for UI/tests (best-effort, read without heavy locking assumptions outside midi lock paths).
struct State {
  uint8_t mode;
  uint8_t master;       // SourceKind
  uint8_t transport;    // Transport
  uint8_t extValid;     // external clock seen recently and usable
  uint8_t clockLost;    // external clock was active and timed out
  uint8_t lostHold;     // in clock-lost hold (no silent fallback)
  int16_t extDev;       // device followed for external clock (-1 none)
  float bpm;            // estimated or internal bpm
  uint32_t pulse;       // external MIDI clock pulses received (24 PPQ), monotonic while valid
  uint32_t seqTicks;    // sequencer subticks to consume (96 PPQ accumulator, 4 per pulse)
};

void begin();

// Mode/source selection. Does not silently restart/jump transport except as documented.
// Returns false if the requested mode cannot be honored safely.
bool setMode(Mode m, int hostDev = -1);
Mode mode();
State state();

// Called for incoming realtime bytes (0xF8/FA/FB/FC/0xF2) from device d, with midi lock held.
// out is the MIDI engine's locked output callback (routing-aware for channel msgs/realtime send).
// Returns true to suppress forwarding/routing of this realtime message (preserve existing behavior,
// e.g. leading clock dropped from device stream), false to allow normal forwarding when thru/routing on.
bool realtimeInLocked(int d, uint8_t b, midi::Out out);

// Called periodically from midi-locked contexts (e.g. play tick) to update loss detection.
void tickLocked(midi::Out out, uint32_t nowMs);

// Internal master pulse (24 PPQ) generated by the unified/internal clock driver, under midi lock.
// Drives consumers (play/arp/beat as applicable, sequencer accumulator) and may emit MIDI clock out.
void internalPulseLocked(midi::Out out);

// Transport control requested locally (UI). Routed according to active mode/master.
void requestStart();
void requestStop();
void requestContinue();
void requestToggle();

// True once, when the clock has just been lost and the sequencer's sounding notes must be let go. The caller
// clears it by taking it, so the notes are released exactly once and no note is ended twice.
//
// It is a flag and not a call into the engine because the clock is lost inside the MIDI lock, and letting a note
// go goes out through midi::bytesIn, which takes that same lock: the sequencer's own thread does the releasing,
// one of its 1 ms turns later.
bool takeNoteRelease();

// ------------------------------------------------------------------------------- leading, as a sequencer ---
// There has always been a clock master here: play.cpp sends 24 PPQ while its clock setting is "lead", at its own
// tempo. What was missing is that the sequencer never owned it - the clock went out at play's tempo while the
// sequencer ran at the pattern's, and starting the sequencer told nobody. internalPulseLocked() and the send
// helpers below it were left unconnected rather than make a second master.
//
// So: while the clock setting is "lead" and the sequencer is running, the sequencer is the master. It sends the
// clock itself, from the same thread and the same sub-tick count that plays its notes, so the clock and the notes
// cannot drift apart; and play's own tick does not send one meanwhile. Stopped, nothing changes: play leads at
// its own tempo as it always did. Following, nothing is sent at all, so an incoming clock is never echoed.
bool seqIsMaster();
// play.cpp tells us when its clock setting is "lead", because asking it would not be safe: play::setup() takes
// the MIDI lock, and seqIsMaster() is asked for from under that lock (play::tickLocked) and from the sequencer's
// own timing thread. Both would be a deadlock or a stall in the worst possible place
void setLeading(bool on);
// The transport message the sequencer's thread should send out (0xFA start, 0xFB continue, 0xFC stop), or 0.
// Taken by the caller, so each is sent once. Always 0 unless we are the one leading
uint8_t takeTransportOut();

// Whether the sequencer should be advanced by its own internal 96 PPQ thread tick.
// In EXTERNAL/host-follow modes with a valid (non-lost-hold) external clock, returns false.
bool seqInternalDrive();
// Consume up to maxSub sequencer subticks produced by external clock pulses. Returns count consumed.
// Used by the sequencer driver to advance deterministically (4 per 0xF8) without extra timers.
int consumeSeqTicks(int maxSub);

// Exposed for tests/harness: simulate time passing for loss detection.
void setNowMs(uint32_t nowMs);
uint32_t nowMs();
uint32_t droppedPulses();
uint32_t latePulses();

// Song Position Pointer (0xF2), 14-bit value in 16th-note units. Applies safe seek behavior.
void sppLocked(uint16_t positionSixteenths, midi::Out out);
// SPP assembly helper for byte-stream parsers: feed data bytes following status.
bool sppFeed(uint8_t b, uint16_t& positionSixteenths);

}  // namespace midisync
